#[test]
fn rejects_invalid_types_and_missing_required_fields() {
    for expression in [
        r"new R.Command {}",
        r#"new R.Timezone { name = "UTC"; state = "present" }"#,
        r#"new R.Command { cmd = "true"; removes = "/tmp/a" }"#,
        r#"new R.Shell { cmd = "true"; removes = "/tmp/a" }"#,
        r"new R.Shell {}",
        r#"new R.Shell { argv = new Listing<String> { "echo" } }"#,
        r#"new R.BlockInFile { path = "/tmp/x" }"#,
        r#"new R.LineInFile { path = "/tmp/x" }"#,
        r#"new R.LineInFile { path = "/tmp/x"; state = "absent" }"#,
        r#"new R.PostgresSchema { name = "a" }"#,
        r#"new R.PostgresPrivileges { role = "a"; type = "table" }"#,
        r#"new R.PostgresPrivileges { login_db = "db"; role = "a"; type = "database" }"#,
        r#"new R.PostgresPrivileges { login_db = "db"; role = "a"; type = "table"; target_roles = "a" }"#,
        r#"new R.VolumeGroup { vg = "a" }"#,
        r#"new R.Sysctl { name = "a" }"#,
        r#"new R.Service { state = "started" }"#,
        r"new R.Service { enabled = true }",
        r#"new R.Firewall { chain = "INPUT"; policy = "DROP"; jump = "ACCEPT" }"#,
        r#"new R.Lookup { provider = "pipe" }"#,
        r#"new R.Command { argv = "echo hello" }"#,
        r#"new R.Apt { upgrade = "garbage" }"#,
        r#"new R.File { path = "/tmp/link"; state = "link" }"#,
        r#"new R.File { path = "a"; dest = "b" }"#,
        r#"new R.Mount { path = "/tmp/mount" }"#,
        r#"new R.Template { src = "a"; dest = "b"; content = "c" }"#,
        r"new R.Assert {}",
        r#"new R.Lookup { provider = "command" }"#,
        r"new R.Command { argv = new Listing<String> {} }",
        r"new R.Ref {}",
        r#"new R.Call { `function` = "eq" }"#,
        r#"new R.Call { `function` = "if"; args { new R.Literal { value = true } } }"#,
        r#"new R.Call { `function` = "map"; args { new R.Literal { value = true } } }"#,
        r#"new R.Apt { state = "garbage" }"#,
        r#"new R.File { path = "/tmp/file"; state = "garbage" }"#,
        r#"new R.File { mode = "0644" }"#,
        r#"new R.Copy { dest = "/tmp/file" }"#,
        r#"new R.Copy { dest = "/tmp/file"; src = "a"; content = "b" }"#,
        r#"new R.PostgresRole { name = "a"; login_port = 70000 }"#,
        r#"new R.PostgresPrivileges { role = "a"; type = "garbage" }"#,
        r"new R.Pause { seconds = -1 }",
        r#"new R.Command { cmd = "x"; argv = new Listing<String> { "x" } }"#,
        r#"new R.Service { state = "unsupported" }"#,
        r#"new R.User { name = "test"; uid = -1 }"#,
        r#"new R.File { path = "/tmp/file"; mode = "not-octal" }"#,
        r#"new R.Task { name = "bad"; operation = new R.Debug {}; block { new R.Task { name = "inner"; operation = new R.Debug {} } } }"#,
        r#"new R.Operation { kind = "unsupported" }"#,
        r#"new R.Apt { kind = "unsupported"; name = "hello" }"#,
        r#"new R.Expr { kind = "unsupported" }"#,
        r#"new R.Call { `function` = "equals" }"#,
        r#"new R.Task { name = "bad"; operation = new { kind = "unsupported" } }"#,
        r#"new R.Filesystem { dev = "/dev/test"; fstype = "btrfs" }"#,
        r#"new R.LogicalVolume { vg = "test"; lv = "data" }"#,
        r#"new R.Host { address = "localhost"; port = 70000 }"#,
    ] {
        assert!(super::evaluate(expression).is_err(), "{expression}");
    }
}
